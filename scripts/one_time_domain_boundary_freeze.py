    path = "80 系统/01 知识库设计说明.md"
    text = read(path)
    text = text.replace("version: 3.4", "version: 3.5", 1)
    text = text.replace(
        "# 个人知识库总体设计方案 v3.4",
        "# 个人知识库总体设计方案 v3.5",
        1,
    )
    marker = "---\n\n# 7. 图形学领域蓝图"
    if marker not in text:
        raise RuntimeError("Could not locate section 7 marker")
    text = text.replace(marker, DESIGN_BOUNDARY_SECTION + "---\n\n# 7. 图形学领域蓝图", 1)
    write(path, text)


